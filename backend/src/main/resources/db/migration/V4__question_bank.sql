
-- V4: QUESTION BANK
-- TOEIC Learning Platform

-- 1. TOEIC Parts
CREATE TABLE toeic_parts (
    part_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_number INTEGER NOT NULL UNIQUE,
    skill VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL
);

-- 2. Topics
CREATE TABLE topics (
    topic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

-- 3. Question Types
CREATE TABLE question_types (
    question_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT
);

-- 4. Question Groups
CREATE TABLE question_groups (
    group_id UUID PRIMARY KEY,
    group_type VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- 5. Questions
CREATE TABLE questions (
    question_id UUID PRIMARY KEY,
    group_id UUID,
    part_id INTEGER NOT NULL,
    topic_id INTEGER,
    question_type_id INTEGER NOT NULL,
    created_by UUID NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_questions_group
        FOREIGN KEY (group_id)
        REFERENCES question_groups(group_id),

    CONSTRAINT fk_questions_part
        FOREIGN KEY (part_id)
        REFERENCES toeic_parts(part_id),

    CONSTRAINT fk_questions_topic
        FOREIGN KEY (topic_id)
        REFERENCES topics(topic_id),

    CONSTRAINT fk_questions_type
        FOREIGN KEY (question_type_id)
        REFERENCES question_types(question_type_id),

    CONSTRAINT fk_questions_creator
        FOREIGN KEY (created_by)
        REFERENCES users(user_id)
);

-- 6. Question Versions
CREATE TABLE question_versions (
    question_version_id UUID PRIMARY KEY,
    question_id UUID NOT NULL,
    group_version_id UUID,
    version_number INTEGER NOT NULL,
    question_text TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    explanation TEXT,
    difficulty VARCHAR(20),
    reviewed_by UUID,
    reviewed_at TIMESTAMPTZ,
    approved_by UUID,
    approved_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_question_versions_question
        FOREIGN KEY (question_id)
        REFERENCES questions(question_id),

    CONSTRAINT fk_question_versions_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES users(user_id),

    CONSTRAINT fk_question_versions_approver
        FOREIGN KEY (approved_by)
        REFERENCES users(user_id),

    CONSTRAINT uq_question_version_number
        UNIQUE (question_id, version_number),

    CONSTRAINT uq_question_version_question
        UNIQUE (question_version_id, question_id),

    CONSTRAINT uq_question_version_group
        UNIQUE (question_version_id, group_version_id)
);

-- 7. Question Choices
CREATE TABLE question_choices (
    choice_id UUID PRIMARY KEY,
    question_version_id UUID NOT NULL,
    choice_label VARCHAR(10) NOT NULL,
    content TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL,
    display_order INTEGER NOT NULL,

    CONSTRAINT fk_question_choices_version
        FOREIGN KEY (question_version_id)
        REFERENCES question_versions(question_version_id),

    CONSTRAINT uq_question_choice_version
        UNIQUE (question_version_id, choice_id),

    CONSTRAINT uq_question_choice_label
        UNIQUE (question_version_id, choice_label),

    CONSTRAINT uq_question_choice_order
        UNIQUE (question_version_id, display_order)
);

-- 8. Question Resources
CREATE TABLE question_resources (
    question_version_id UUID NOT NULL,
    resource_id UUID NOT NULL,

    PRIMARY KEY (question_version_id, resource_id),

    CONSTRAINT fk_question_resources_version
        FOREIGN KEY (question_version_id)
        REFERENCES question_versions(question_version_id),

    CONSTRAINT fk_question_resources_resource
        FOREIGN KEY (resource_id)
        REFERENCES media_resources(resource_id)
);

-- Indexes
CREATE INDEX idx_questions_group
    ON questions(group_id);

CREATE INDEX idx_questions_part
    ON questions(part_id);

CREATE INDEX idx_questions_topic
    ON questions(topic_id);

CREATE INDEX idx_questions_type
    ON questions(question_type_id);

CREATE INDEX idx_questions_creator
    ON questions(created_by);

CREATE INDEX idx_question_versions_question
    ON question_versions(question_id);

CREATE INDEX idx_question_choices_version
    ON question_choices(question_version_id);

CREATE INDEX idx_question_resources_resource
    ON question_resources(resource_id);
