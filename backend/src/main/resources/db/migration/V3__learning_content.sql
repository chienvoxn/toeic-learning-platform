
-- =====================================================
-- V3: LEARNING CONTENT
-- TOEIC Learning Platform
-- =====================================================

-- 1. Content Categories
CREATE TABLE content_categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT
);

-- 2. Learning Contents
CREATE TABLE learning_contents (
    content_id UUID PRIMARY KEY,
    current_published_version_id UUID,
    category_id INTEGER NOT NULL,
    author_id UUID NOT NULL,
    title VARCHAR(255) NOT NULL,
    summary TEXT,
    body TEXT,
    difficulty VARCHAR(20),
    status VARCHAR(20) NOT NULL,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_learning_contents_category
        FOREIGN KEY (category_id)
        REFERENCES content_categories(category_id),

    CONSTRAINT fk_learning_contents_author
        FOREIGN KEY (author_id)
        REFERENCES users(user_id),

    CONSTRAINT uq_learning_contents_published_version
        UNIQUE (content_id, current_published_version_id)
);

-- 3. Media Resources
CREATE TABLE media_resources (
    resource_id UUID PRIMARY KEY,
    resource_type VARCHAR(30) NOT NULL,
    storage_url TEXT NOT NULL,
    mime_type VARCHAR(100),
    file_size BIGINT,
    duration_seconds INTEGER,
    transcript TEXT,
    created_at TIMESTAMPTZ NOT NULL
);

-- 4. Content Resources
CREATE TABLE content_resources (
    content_id UUID NOT NULL,
    resource_id UUID NOT NULL,

    PRIMARY KEY (content_id, resource_id),

    CONSTRAINT fk_content_resources_content
        FOREIGN KEY (content_id)
        REFERENCES learning_contents(content_id),

    CONSTRAINT fk_content_resources_resource
        FOREIGN KEY (resource_id)
        REFERENCES media_resources(resource_id)
);

-- 5. Learning Progress
CREATE TABLE learning_progress (
    progress_id UUID PRIMARY KEY,
    completed_content_version_id UUID,
    user_id UUID NOT NULL,
    content_id UUID NOT NULL,
    status VARCHAR(20) NOT NULL,
    progress_percent DECIMAL(5,2),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    last_accessed_at TIMESTAMPTZ,

    CONSTRAINT fk_learning_progress_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_learning_progress_content
        FOREIGN KEY (content_id)
        REFERENCES learning_contents(content_id),

    CONSTRAINT uq_learning_progress_user_content
        UNIQUE (user_id, content_id),

    CONSTRAINT chk_learning_progress_percent
        CHECK (
            progress_percent IS NULL
            OR progress_percent BETWEEN 0 AND 100
        )
);

-- 6. Bookmarks
CREATE TABLE bookmarks (
    user_id UUID NOT NULL,
    content_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,

    PRIMARY KEY (user_id, content_id),

    CONSTRAINT fk_bookmarks_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_bookmarks_content
        FOREIGN KEY (content_id)
        REFERENCES learning_contents(content_id)
);

-- Indexes for frequently queried foreign keys
CREATE INDEX idx_learning_contents_category
    ON learning_contents(category_id);

CREATE INDEX idx_learning_contents_author
    ON learning_contents(author_id);

CREATE INDEX idx_content_resources_resource
    ON content_resources(resource_id);

CREATE INDEX idx_learning_progress_content
    ON learning_progress(content_id);

CREATE INDEX idx_bookmarks_content
    ON bookmarks(content_id);
