import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("../", import.meta.url));
const manifest = JSON.parse(
  await readFile(path.join(root, "assets/asset-manifest.json"), "utf8"),
);
const check = process.argv.includes("--check");
const imports = [];
const seenIds = new Set();
const seenPaths = new Set();
let missing = 0;

for (const asset of manifest.assets) {
  if (seenIds.has(asset.id) || seenPaths.has(asset.relativePath))
    throw new Error(`Duplicate asset: ${asset.id}`);
  seenIds.add(asset.id);
  seenPaths.add(asset.relativePath);
  const destination = path.resolve(root, asset.relativePath);
  if (
    !destination.startsWith(path.join(root, "assets", "images") + path.sep) ||
    path.extname(destination) !== ".png"
  ) {
    throw new Error(
      `Asset destination must be a PNG under assets/images/: ${asset.id}`,
    );
  }
  if (asset.referencePath)
    await readFile(path.resolve(root, asset.referencePath));
  if (asset.sourcePath) await readFile(path.resolve(root, asset.sourcePath));
  let buffer;
  try {
    buffer = await readFile(destination);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    missing += 1;
    console.log(`PENDING ${asset.id}: ${asset.relativePath}`);
    continue;
  }
  if (
    buffer.length < 24 ||
    buffer.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a" ||
    !buffer.readUInt32BE(16) ||
    !buffer.readUInt32BE(20)
  ) {
    throw new Error(`Invalid PNG: ${asset.relativePath}`);
  }
  if (
    asset.width &&
    (buffer.readUInt32BE(16) !== asset.width ||
      buffer.readUInt32BE(20) !== asset.height)
  )
    throw new Error(`Image geometry changed: ${asset.relativePath}`);
  if (
    asset.sha256 &&
    createHash("sha256").update(buffer).digest("hex") !== asset.sha256
  )
    throw new Error(
      `Image differs from the imported source: ${asset.relativePath}`,
    );
  imports.push(
    `  ${JSON.stringify(asset.id)}: require(${JSON.stringify("../../" + asset.relativePath)}),`,
  );
}

const generated =
  "// Generated by scripts/sync-assets.mjs. Runtime sources are static Metro requires.\n" +
  "export const images = Object.freeze({\n" +
  imports.join("\n") +
  "\n});\n";
const registryPath = path.join(root, "src/assets/images.generated.js");
if (check) {
  if (missing) throw new Error(`${missing} required images missing.`);
  const actual = await readFile(registryPath, "utf8");
  if (actual.replace(/\r\n/g, "\n") !== generated)
    throw new Error("Image registry is stale. Run npm run assets:sync.");
} else {
  // Chỉ tạo thư mục tải ảnh bên trong app, không tải từ URL tạm hết hạn.
  for (const asset of manifest.assets)
    await mkdir(path.dirname(path.resolve(root, asset.relativePath)), {
      recursive: true,
    });
  await writeFile(registryPath, generated);
}
console.log(
  `${check ? "CHECKED" : "SYNCED"} ${imports.length} local images; ${missing} pending exports. Missing exports do not indicate visual PASS.`,
);
